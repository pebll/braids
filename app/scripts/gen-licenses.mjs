// Regenerates app/THIRD_PARTY_LICENSES: the license texts of the app's
// runtime dependencies (npm packages bundled into the UI, Rust crates linked
// into the Tauri shell, Linux build). The top-level CMakeLists.txt combines it
// with the other fragments. Maintainer tool: rerun after dependency updates
// (npm install, cargo update) and commit the result.
//
// Usage: node scripts/gen-licenses.mjs   (from app/, needs node_modules and cargo)

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function licenseTexts(dir) {
  let names = [];
  try {
    names = fs.readdirSync(dir).filter((n) => LICENSE_FILE.test(n)).sort();
  } catch {
    return [];
  }
  return names.map((n) => fs.readFileSync(path.join(dir, n), 'utf8').replace(/\r\n/g, '\n').trim());
}

// name@version -> { license, texts }
const entries = [];

// npm: production dependencies from the lock file
const lock = JSON.parse(fs.readFileSync(path.join(appDir, 'package-lock.json'), 'utf8'));
for (const [key, info] of Object.entries(lock.packages)) {
  if (!key || info.dev) continue;
  const name = key.replace(/^.*node_modules\//, '');
  entries.push({ id: `${name} ${info.version} (npm)`, license: info.license ?? 'see text', texts: licenseTexts(path.join(appDir, key)) });
}

// cargo: crates reachable through normal (non-build, non-dev) dependencies
const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--filter-platform', 'x86_64-unknown-linux-gnu'],
  { cwd: path.join(appDir, 'src-tauri'), maxBuffer: 256 << 20 }).toString());
const packages = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const seen = new Set();
const queue = [meta.resolve.root];
while (queue.length) {
  const id = queue.shift();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
  }
}
for (const id of seen) {
  const p = packages.get(id);
  if (!p || id === meta.resolve.root) continue;
  entries.push({ id: `${p.name} ${p.version} (crate)`, license: p.license ?? 'see text', texts: licenseTexts(path.dirname(p.manifest_path)) });
}

// group packages with identical license texts
const groups = new Map();
for (const e of entries.sort((a, b) => a.id.localeCompare(b.id))) {
  const key = e.texts.length ? e.texts.join('\n\n----\n\n') : `(no license file; declared license: ${e.license})`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(`${e.id}: ${e.license}`);
}

const rule = '-'.repeat(80);
let out = `${'='.repeat(80)}
braids third-party licenses: desktop app (UI and Tauri shell)
${'='.repeat(80)}

Generated by app/scripts/gen-licenses.mjs from package-lock.json and
Cargo.lock; do not edit by hand.
`;
for (const [text, ids] of [...groups.entries()].sort((a, b) => a[1][0].localeCompare(b[1][0]))) {
  out += `\n${rule}\n${ids.join('\n')}\n${rule}\n\n${text}\n`;
}
fs.writeFileSync(path.join(appDir, 'THIRD_PARTY_LICENSES'), out);
console.log(`${entries.length} packages, ${groups.size} distinct license texts`);
